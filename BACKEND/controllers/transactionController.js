const deleteTransaction = async (req, res) => {
  try {
    const transaction = await Transaction.findById(req.params.id);

    if (!transaction) {
      return res.status(404).json({
        message: 'Transaction not found',
      });
    }

    // Reverse Bill Payments
    if (transaction.relatedBills?.length) {
      for (const relBill of transaction.relatedBills) {
        const bill = await Bill.findById(relBill.billId);
        if (bill) {
          bill.paymentRecords = bill.paymentRecords.filter(
            (pr) =>
              pr.transactionId &&
              pr.transactionId.toString() !== transaction._id.toString()
          );

          bill.totalPaidAmount = bill.paymentRecords.reduce(
            (sum, pr) => sum + pr.amountPaid,
            0
          );

          await bill.save();
        }
      }
    }

    // reverse intrest note payments
          if (
        transaction.relatedInterestNotes &&
        transaction.relatedInterestNotes.length > 0
      ) {
        for (const relNote of transaction.relatedInterestNotes) {
          const interestNote = await InterestNote.findById(
            relNote.interestNoteId
          );

          if (interestNote) {
            interestNote.paymentRecords =
              interestNote.paymentRecords.filter(
                (pr) =>
                  pr.transactionId &&
                  pr.transactionId.toString() !==
                    transaction._id.toString()
              );

            interestNote.totalPaidAmount =
              interestNote.paymentRecords.reduce(
                (sum, p) => sum + p.amountPaid,
                0
              );

            if (interestNote.totalPaidAmount <= 0) {
              interestNote.status = 'Pending';
            } else if (
              interestNote.totalPaidAmount <
              interestNote.totalAmount
            ) {
              interestNote.status = 'Partially Paid';
            } else {
              interestNote.status = 'Paid';
            }

            await interestNote.save();
          }
        }
      }

    // Reverse Purchase Payments
    if (transaction.relatedPurchases?.length) {
      for (const relPurchase of transaction.relatedPurchases) {
        const purchase = await Purchase.findById(relPurchase.purchaseId);
        if (purchase) {
          purchase.paymentRecords = purchase.paymentRecords.filter(
            (pr) =>
              pr.transactionId &&
              pr.transactionId.toString() !== transaction._id.toString()
          );

          purchase.totalPaidAmount = purchase.paymentRecords.reduce(
            (sum, pr) => sum + pr.amountPaid,
            0
          );

          await purchase.save();
        }
      }
    }

    await transaction.deleteOne();

    res.json({
      message: 'Transaction removed successfully.',
    });
  } catch (error) {
    log(`Error deleting transaction: ${error.message}`, 'error');
    res.status(500).json({
      message: 'Server error while deleting transaction.',
    });
  }
};

