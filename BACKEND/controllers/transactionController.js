const updateTransaction = async (req, res) => {
  const { notes, referenceNumber, description, paymentDate, paymentMethod } =
    req.body;

  try {
    const transaction = await Transaction.findById(req.params.id);

    if (!transaction) {
      return res.status(404).json({
        message: 'Transaction not found',
      });
    }

    if (
      req.body.amount ||
      req.body.type ||
      req.body.relatedBillIds ||
      req.body.relatedPurchaseIds ||
      req.body.companyId
    ) {
      return res.status(400).json({
        message:
          'Amount, type, company, or related bills/purchases cannot be directly updated.',
      });
    }

    if (notes !== undefined) transaction.notes = notes;
    if (referenceNumber !== undefined)
      transaction.referenceNumber = referenceNumber;
    if (description !== undefined) transaction.description = description;
    if (paymentDate !== undefined)
      transaction.paymentDate = new Date(paymentDate);
    if (paymentMethod !== undefined)
      transaction.paymentMethod = paymentMethod;

    const updatedTransaction = await transaction.save();
    res.json(updatedTransaction);
  } catch (error) {
    log(`Error updating transaction: ${error.message}`, 'error');
    res.status(500).json({
      message: 'Server error while updating transaction.',
    });
  }
};

