const getFilteredTransactionSummary = async (req, res) => {
  try {
    const { companyId, workerId, category, type, paymentMethod, startDate, endDate, month, year } = req.query;

    console.log('[SUMMARY DEBUG] req.organizationId:', req.organizationId);
    console.log('[SUMMARY DEBUG] Query params:', JSON.stringify(req.query));

    const matchStage = { organizationId: new mongoose.Types.ObjectId(req.organizationId) };

    if (companyId) matchStage.company = new mongoose.Types.ObjectId(companyId);
    if (workerId) matchStage.worker = new mongoose.Types.ObjectId(workerId);
    if (category) matchStage.category = category;
    if (type) matchStage.type = type;
    if (paymentMethod) matchStage.paymentMethod = paymentMethod;

    if (month && year) {
      const firstDay = new Date(Date.UTC(year, parseInt(month) - 1, 1));
      const lastDay = new Date(Date.UTC(year, parseInt(month), 0, 23, 59, 59, 999));
      matchStage.paymentDate = { $gte: firstDay, $lte: lastDay };
    } else if (startDate && endDate) {
      matchStage.paymentDate = {
        $gte: new Date(startDate),
        $lte: new Date(new Date(endDate).setHours(23, 59, 59, 999)),
      };
    } else if (startDate) {
      matchStage.paymentDate = { $gte: new Date(startDate) };
    } else if (endDate) {
      matchStage.paymentDate = { $lte: new Date(new Date(endDate).setHours(23, 59, 59, 999)) };
    }

    console.log('[SUMMARY DEBUG] matchStage:', JSON.stringify(matchStage, null, 2));

    const totalDocs = await Transaction.countDocuments({ organizationId: req.organizationId });
    console.log('[SUMMARY DEBUG] Total transactions for this org:', totalDocs);

    const summary = await Transaction.aggregate([
      { $match: matchStage },
      {
        $group: {
          _id: '$type',
          totalAmount: { $sum: '$amount' },
        },
      },
    ]);

    console.log('[SUMMARY DEBUG] Aggregate result:', JSON.stringify(summary));

    let filteredTotalIn = 0;
    let filteredTotalOut = 0;

    summary.forEach((item) => {
      if (item._id === 'IN') filteredTotalIn = item.totalAmount;
      if (item._id === 'OUT') filteredTotalOut = item.totalAmount;
    });

    console.log('[SUMMARY DEBUG] Response:', { filteredTotalIn, filteredTotalOut });

    res.json({ filteredTotalIn, filteredTotalOut });
  } catch (error) {
    console.error('[SUMMARY DEBUG] Error:', error.message);
    log(`Error fetching summary: ${error.message}`, 'error');
    res.status(500).json({ message: 'Server error while fetching summary.' });
  }
};

