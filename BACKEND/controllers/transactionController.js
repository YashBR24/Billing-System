const exportTransactionsToExcel = async (req, res) => {
  try {
    const {
      companyId,
      workerId,
      category,
      type,
      paymentMethod,
      startDate,
      endDate,
      month,
      year,
    } = req.query;

    const query = {};

    if (companyId) query.company = companyId;
    if (workerId) query.worker = workerId;
    if (category) query.category = category;
    if (type) query.type = type;
    if (paymentMethod) query.paymentMethod = paymentMethod;

    if (month && year) {
      const firstDay = new Date(Date.UTC(year, parseInt(month) - 1, 1));
      const lastDay = new Date(
        Date.UTC(year, parseInt(month), 0, 23, 59, 59, 999)
      );
      query.paymentDate = { $gte: firstDay, $lte: lastDay };
    } else if (startDate && endDate) {
      query.paymentDate = {
        $gte: new Date(startDate),
        $lte: new Date(new Date(endDate).setHours(23, 59, 59, 999)),
      };
    }

    const transactions = await Transaction.find(query)
      .populate('company', 'name')
      .populate('worker', 'name')
      .populate('recordedBy', 'username')
      .sort({ paymentDate: -1, createdAt: -1 });

    const workbook = new ExcelJS.Workbook();
    const worksheet = workbook.addWorksheet('Transactions');

    worksheet.columns = [
      { header: 'ID', key: 'id', width: 12 },
      { header: 'Date', key: 'date', width: 15 },
      { header: 'Type', key: 'type', width: 10 },
      { header: 'Category', key: 'category', width: 25 },
      {
        header: 'Amount',
        key: 'amount',
        width: 15,
        style: { numFmt: '#,##0.00' },
      },
      { header: 'Company', key: 'company', width: 20 },
      { header: 'Worker', key: 'worker', width: 20 },
      { header: 'Payment Method', key: 'paymentMethod', width: 18 },
      { header: 'Reference', key: 'reference', width: 20 },
      { header: 'Description', key: 'description', width: 45 },
      { header: 'Related Bills', key: 'relatedBills', width: 25 },
      { header: 'Related Purchases', key: 'relatedPurchases', width: 25 },
      {
        header: 'Related Interest Notes',
        key: 'relatedInterestNotes',
        width: 25,
      },
      { header: 'Recorded By', key: 'recordedBy', width: 20 },
      { header: 'Notes', key: 'notes', width: 40 },
    ];

    transactions.forEach((transaction) => {
      worksheet.addRow({
        id: transaction._id.toString(),
        date: transaction.paymentDate.toISOString().split('T')[0],
        type: transaction.type,
        category: transaction.category,
        amount: transaction.amount,
        company: transaction.company?.name || 'N/A',
        worker: transaction.worker?.name || 'N/A',
        paymentMethod: transaction.paymentMethod,
        reference: transaction.referenceNumber || '',
        description: transaction.description || '',
        relatedBills:
          transaction.relatedBills
            ?.map((b) => b.billNumber)
            .join(', ') || '',
        relatedPurchases:
          transaction.relatedPurchases
            ?.map((p) => p.purchaseBillNumber)
            .join(', ') || '',
        relatedInterestNotes:
          transaction.relatedInterestNotes
            ?.map((i) => i.interestNoteNumber)
            .join(', ') || '',
        recordedBy: transaction.recordedBy?.username || 'System',
        notes: transaction.notes || '',
      });
    });

    worksheet.getRow(1).eachCell((cell) => {
      cell.font = { bold: true };
      cell.fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: 'FFD3D3D3' },
      };
    });

    res.setHeader(
      'Content-Type',
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    );
    res.setHeader(
      'Content-Disposition',
      `attachment; filename=transactions_${
        new Date().toISOString().split('T')[0]
      }.xlsx`
    );

    await workbook.xlsx.write(res);
    res.end();

    log(`Exported ${transactions.length} transactions to Excel`, 'info');
  } catch (error) {
    log(`Error exporting transactions to Excel: ${error.message}`, 'error');
    res.status(500).json({
      message: 'Server error while exporting transactions to Excel.',
    });
  }
};


