const getFilteredTransactionSummary = async (req, res) => {
  try {
    const summary = await Transaction.aggregate([
      {
        $group: {
          _id: '$type',
          totalAmount: { $sum: '$amount' },
        },
      },
    ]);

    let filteredTotalIn = 0;
    let filteredTotalOut = 0;

    summary.forEach((item) => {
      if (item._id === 'IN') filteredTotalIn = item.totalAmount;
      if (item._id === 'OUT') filteredTotalOut = item.totalAmount;
    });

    res.json({
      filteredTotalIn,
      filteredTotalOut,
    });
  } catch (error) {
    log(`Error fetching summary: ${error.message}`, 'error');
    res.status(500).json({
      message: 'Server error while fetching summary.',
    });
  }
};

