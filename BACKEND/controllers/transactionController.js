const createTransaction = async (req, res) => {
  const {
    paymentDate,
    type,
    companyId,
    workerId,
    category,
    relatedBillIds,
    relatedPurchaseIds,
    relatedInterestNoteIds,
    amount,
    paymentMethod,
    referenceNumber,
    description,
    notes,
  } = req.body;

  if (!paymentDate || !type || !amount || !paymentMethod || !category) {
    return res.status(400).json({
      message:
        'Payment date, type, amount, payment method, and category are required.',
    });
  }

  if (parseFloat(amount) <= 0) {
    return res.status(400).json({
      message: 'Transaction amount must be positive.',
    });
  }

  try {
    let savedTransaction = null;

    let companyObjectId = null;
    if (companyId) {
      const company = await Company.findById(companyId);
      if (!company) {
        return res.status(404).json({
          message: 'Associated company not found.',
        });
      }
      companyObjectId = company._id;
    }

    let workerObjectId = null;
    if (workerId) {
      const worker = await Worker.findById(workerId);
      if (!worker) {
        return res.status(404).json({
          message: 'Associated worker not found.',
        });
      }
      workerObjectId = worker._id;
    }

    let autoGeneratedDescription = description || category;

    if (category === 'Salary' && workerObjectId) {
      const worker = await Worker.findById(workerObjectId);
      autoGeneratedDescription = `Salary paid to ${worker?.name || 'worker'}`;
    }

    const initialTransactionData = {
      paymentDate: new Date(paymentDate),
      type,
      company: companyObjectId,
      worker: workerObjectId,
      category,
      amount: parseFloat(amount),
      paymentMethod,
      referenceNumber,
      description: autoGeneratedDescription,
      notes,
      recordedBy: req.user._id,
      organizationId: req.organizationId,

      relatedBills: (relatedBillIds || []).map((id) => ({
        billId: id,
      })),

      relatedPurchases: (relatedPurchaseIds || []).map((id) => ({
        purchaseId: id,
      })),

      relatedInterestNotes: (relatedInterestNoteIds || []).map((id) => ({
        interestNoteId: id,
      })),
    };

    const newTransaction = new Transaction(initialTransactionData);
    savedTransaction = await newTransaction.save();

    let needsTransactionUpdate = false;

    let finalRelatedBills = [];
    let finalRelatedPurchases = [];
    let finalRelatedInterestNotes = [];

    // ================= BILL PAYMENT =================
    if (
      type === 'IN' &&
      category === 'BillPayment' &&
      relatedBillIds?.length > 0
    ) {
      let billNumbers = [];

      // Fetch selected bills, de-duplicating the ids sent by the client.
      const billDocs = [];
      const seenBillIds = new Set();
      for (const billId of relatedBillIds) {
        if (!billId || seenBillIds.has(String(billId))) continue;
        seenBillIds.add(String(billId));
        const bill = await Bill.findById(billId);
        if (bill) billDocs.push(bill);
      }

      // Settle OLDEST bills first. The remaining (partial) amount is therefore
      // absorbed by the NEWEST/latest selected bill — NOT the older bill.
      billDocs.sort(
        (a, b) => new Date(a.billDate) - new Date(b.billDate)
      );

      const round2 = (n) => Math.round((n + Number.EPSILON) * 100) / 100;
      const transactionAmount = round2(parseFloat(amount));

      // Outstanding amount for every selected bill.
      const eligibleDocs = billDocs
        .map((bill) => ({
          bill,
          outstanding: Math.max(0, round2(bill.totalAmount - (bill.totalPaidAmount || 0))),
        }))
        .filter((d) => d.outstanding > 0);

      if (eligibleDocs.length > 0) {
        let remainingAmount = transactionAmount;

        const recordPaymentOnBill = async (doc, recordAmount) => {
          const { bill } = doc;
          bill.paymentRecords.push({
            paymentDate: savedTransaction.paymentDate,
            amountPaid: recordAmount,
            transactionId: savedTransaction._id,
            paymentMethod,
            referenceNumber,
            notes: `Bill payment via transaction ${savedTransaction._id}`,
          });

          bill.totalPaidAmount = round2(bill.totalPaidAmount + recordAmount);
          await bill.save();

          finalRelatedBills.push({
            billId: bill._id,
            billNumber: bill.billNumber,
          });

          billNumbers.push(bill.billNumber);
        };

        // Settle selected bills oldest-first: each bill is either cleared fully
        // or absorbs whatever part of the amount remains. The oldest bills are
        // marked Paid and the NEWEST selected bill takes the remaining due.
        // e.g. amount 152033 → bill10 (133347, older) becomes Paid, remaining
        // 18686 goes to bill12 (newest) → Partially Paid (due 42481).
        for (const doc of eligibleDocs) {
          const { bill, outstanding } = doc;
          if (outstanding <= 0 || remainingAmount <= 0) continue;

          const amountForThisBill = Math.min(remainingAmount, outstanding);
          remainingAmount = round2(remainingAmount - amountForThisBill);

          if (amountForThisBill > 0) {
            await recordPaymentOnBill(doc, amountForThisBill);
          }
        }
      }

      if (billNumbers.length > 0) {
        autoGeneratedDescription = `Payment received for Bill(s): ${billNumbers.join(', ')}`;
        needsTransactionUpdate = true;
      }
    }

    // ================= INTEREST NOTE PAYMENT =================
    else if (
      type === 'IN' &&
      category === 'InterestNotePayment' &&
      relatedInterestNoteIds?.length > 0
    ) {
      let interestNoteNumbers = [];

      const noteDocs = [];
      for (const noteId of relatedInterestNoteIds) {
        const interestNote = await InterestNote.findById(noteId);
        if (interestNote) noteDocs.push(interestNote);
      }

      let remainingAmount = parseFloat(amount);
      for (const interestNote of noteDocs) {
        interestNote.paymentRecords = interestNote.paymentRecords || [];
        interestNote.totalPaidAmount = interestNote.totalPaidAmount || 0;

        const noteOutstanding = Math.max(0, interestNote.totalAmount - interestNote.totalPaidAmount);
        if (noteOutstanding <= 0 || remainingAmount <= 0) continue;

        const amountForThisNote = Math.min(remainingAmount, noteOutstanding);
        remainingAmount = Math.round((remainingAmount - amountForThisNote) * 100) / 100;

        if (amountForThisNote > 0) {
          interestNote.paymentRecords.push({
            paymentDate: savedTransaction.paymentDate,
            amountPaid: amountForThisNote,
            transactionId: savedTransaction._id,
            paymentMethod,
            referenceNumber,
            notes: `Interest note payment via transaction ${savedTransaction._id}`,
          });

          interestNote.totalPaidAmount = Math.round((interestNote.totalPaidAmount + amountForThisNote) * 100) / 100;

          interestNote.status =
            interestNote.totalPaidAmount >= interestNote.totalAmount
              ? 'Paid'
              : 'Partially Paid';

          await interestNote.save();
        }

        finalRelatedInterestNotes.push({
          interestNoteId: interestNote._id,
          interestNoteNumber: interestNote.interestNoteNumber,
        });

        interestNoteNumbers.push(interestNote.interestNoteNumber);
      }

      autoGeneratedDescription = `Interest Note Payment received: ${interestNoteNumbers.join(', ')}`;
      needsTransactionUpdate = true;
    }

    // ================= PURCHASE PAYMENT =================
    else if (
      type === 'OUT' &&
      category === 'PurchasePayment' &&
      relatedPurchaseIds?.length > 0
    ) {
      let purchaseNumbers = [];

      const purchaseDocs = [];
      for (const purchaseId of relatedPurchaseIds) {
        const purchase = await Purchase.findById(purchaseId);
        if (purchase) purchaseDocs.push(purchase);
      }

      let remainingAmount = parseFloat(amount);
      for (const purchase of purchaseDocs) {
        const purchaseOutstanding = Math.max(0, purchase.amount - (purchase.totalPaidAmount || 0));
        if (purchaseOutstanding <= 0 || remainingAmount <= 0) continue;

        const amountForThisPurchase = Math.min(remainingAmount, purchaseOutstanding);
        remainingAmount = Math.round((remainingAmount - amountForThisPurchase) * 100) / 100;

        if (amountForThisPurchase > 0) {
          purchase.paymentRecords.push({
            paymentDate: savedTransaction.paymentDate,
            amountPaid: amountForThisPurchase,
            transactionId: savedTransaction._id,
            paymentMethod,
            referenceNumber,
          });

          purchase.totalPaidAmount = Math.round(((purchase.totalPaidAmount || 0) + amountForThisPurchase) * 100) / 100;
          await purchase.save();
        }

        finalRelatedPurchases.push({
          purchaseId: purchase._id,
          purchaseBillNumber: purchase.purchaseBillNumber,
        });

        purchaseNumbers.push(purchase.purchaseBillNumber);
      }

      autoGeneratedDescription = `Payment made for Purchase Bill(s): ${purchaseNumbers.join(', ')}`;
      needsTransactionUpdate = true;
    }

    if (needsTransactionUpdate) {
      savedTransaction.description = autoGeneratedDescription;
      savedTransaction.relatedBills = finalRelatedBills;
      savedTransaction.relatedPurchases = finalRelatedPurchases;
      savedTransaction.relatedInterestNotes =
        finalRelatedInterestNotes;

      await savedTransaction.save();
    }

    log(
      `Transaction ${savedTransaction.type} (${savedTransaction.category}) created successfully`,
      'info'
    );

    res.status(201).json(savedTransaction);
  } catch (error) {
    // Best-effort rollback: if a linked document save failed mid-way, undo the
    // partial payment updates and remove the transaction so no orphan records /
    // half-updated bills are left behind (a single transaction may pay many bills).
    if (savedTransaction) {
      try {
        const transactionId = savedTransaction._id.toString();

        for (const billId of relatedBillIds || []) {
          const bill = await Bill.findById(billId);
          if (!bill) continue;
          const before = bill.paymentRecords.length;
          bill.paymentRecords = bill.paymentRecords.filter(
            (pr) =>
              !pr.transactionId ||
              pr.transactionId.toString() !== transactionId
          );
          if (bill.paymentRecords.length !== before) {
            bill.totalPaidAmount = bill.paymentRecords.reduce(
              (sum, pr) => sum + (pr.amountPaid || 0),
              0
            );
            await bill.save();
          }
        }

        for (const purchaseId of relatedPurchaseIds || []) {
          const purchase = await Purchase.findById(purchaseId);
          if (!purchase) continue;
          const before = (purchase.paymentRecords || []).length;
          purchase.paymentRecords = (purchase.paymentRecords || []).filter(
            (pr) =>
              !pr.transactionId ||
              pr.transactionId.toString() !== transactionId
          );
          if ((purchase.paymentRecords || []).length !== before) {
            purchase.totalPaidAmount = (purchase.paymentRecords || []).reduce(
              (sum, pr) => sum + (pr.amountPaid || 0),
              0
            );
            await purchase.save();
          }
        }

        for (const noteId of relatedInterestNoteIds || []) {
          const interestNote = await InterestNote.findById(noteId);
          if (!interestNote) continue;
          const before = (interestNote.paymentRecords || []).length;
          interestNote.paymentRecords = (interestNote.paymentRecords || []).filter(
            (pr) =>
              !pr.transactionId ||
              pr.transactionId.toString() !== transactionId
          );
          if ((interestNote.paymentRecords || []).length !== before) {
            interestNote.totalPaidAmount = (interestNote.paymentRecords || []).reduce(
              (sum, pr) => sum + (pr.amountPaid || 0),
              0
            );
            interestNote.status =
              (interestNote.totalPaidAmount || 0) <= 0
                ? 'Pending'
                : interestNote.totalPaidAmount >= interestNote.totalAmount
                  ? 'Paid'
                  : 'Partially Paid';
            await interestNote.save();
          }
        }

        await savedTransaction.deleteOne();
        log(
          `Rolled back transaction ${savedTransaction._id} after partial failure`,
          'warn'
        );
      } catch (rollbackError) {
        log(
          `Failed to roll back transaction ${savedTransaction?._id}: ${rollbackError.message}`,
          'error'
        );
      }
    }

    log(
      `Error creating transaction: ${error.message} - Stack: ${error.stack}`,
      'error'
    );

    res.status(500).json({
      message: 'Server error while creating transaction.',
    });
  }
};

