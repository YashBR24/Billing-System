const exportTransactionsToPDF = async (req, res) => {
  try {
    const org = await getOrgDetails(req.organizationId);
    const { companyId, workerId, category, type, paymentMethod, startDate, endDate, month, year } = req.query;
    const query = { organizationId: req.organizationId };

    if (companyId) query.company = companyId;
    if (workerId) query.worker = workerId;
    if (category) query.category = category;
    if (type) query.type = type;
    if (paymentMethod) query.paymentMethod = paymentMethod;

    if (month && year) {
      const firstDay = new Date(Date.UTC(year, parseInt(month) - 1, 1));
      const lastDay = new Date(Date.UTC(year, parseInt(month), 0, 23, 59, 59, 999));
      query.paymentDate = { $gte: firstDay, $lte: lastDay };
    } else if (startDate && endDate) {
      query.paymentDate = { $gte: new Date(startDate), $lte: new Date(new Date(endDate).setHours(23, 59, 59, 999)) };
    } else if (startDate) {
      query.paymentDate = { $gte: new Date(startDate) };
    } else if (endDate) {
      query.paymentDate = { $lte: new Date(new Date(endDate).setHours(23, 59, 59, 999)) };
    }

    const transactions = await Transaction.find(query)
      .populate('company', 'name')
      .populate('worker', 'name')
      .populate('recordedBy', 'username')
      .sort({ paymentDate: 1, createdAt: 1 });

    const myCompany = {
      name: org.name,
      address: org.address,
      gstNumber: org.gstin,
      mobileNumber: null,
    };

    let companyName = null;
    if (companyId) {
      const company = await Company.findById(companyId).select('name');
      companyName = company ? company.name : 'Unknown Company';
    }

    const doc = new PDFDocument({
      margin: 0,
      size: 'A4',
      layout: 'portrait',
    });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename=transactions_${new Date().toISOString().split('T')[0]}.pdf`
    );

    doc.pipe(res);

    const pageWidth = 595.28;
    const pageHeight = 841.89;
    const margin = 20;
    const contentWidth = pageWidth - margin * 2;

    const colWidths = [40, 70, 180, 130, 95];
    const colHeaders = ['Sr.', 'Date', 'Description', 'Company / Worker', 'Amount (Rs.)'];
    const tableTop = 160;
    const tableLeft = margin;
    const tableWidth = colWidths.reduce((a, b) => a + b, 0);

    const totalIn = transactions.filter(t => t.type === 'IN').reduce((sum, t) => sum + t.amount, 0);
    const totalOut = transactions.filter(t => t.type === 'OUT').reduce((sum, t) => sum + t.amount, 0);
    const netBalance = totalIn - totalOut;

    let openingBalance = 0;
    const sortedAsc = transactions.sort((a, b) => new Date(a.paymentDate) - new Date(b.paymentDate));

    const drawPageHeader = () => {
      let y = 12;

      doc.rect(0, 0, pageWidth, 90).fill('#1a237e');

      if (myCompany) {
        doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(20)
          .text(myCompany.name, margin, y, { width: contentWidth, align: 'center' });
        y += 24;

        doc.font('Helvetica').fontSize(9)
          .text(myCompany.address || '', margin, y, { width: contentWidth, align: 'center' });
        y += 14;

        let contactLine = '';
        if (myCompany.gstNumber) contactLine += `GSTIN: ${myCompany.gstNumber}`;
        if (myCompany.mobileNumber) contactLine += `  |  Mobile: ${myCompany.mobileNumber}`;
        if (contactLine) {
          doc.fontSize(8).text(contactLine, margin, y, { width: contentWidth, align: 'center' });
        }
      } else {
        doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(18)
          .text('TRANSACTION STATEMENT', margin, y, { width: contentWidth, align: 'center' });
      }

      doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(12)
        .text('TRANSACTION STATEMENT', margin, 70, { width: contentWidth, align: 'center' });

      let periodText = '';
      if (month && year) {
        const monthName = new Intl.DateTimeFormat('en-US', { month: 'long' }).format(new Date(year, month - 1));
        periodText = `${monthName} ${year}`;
      } else if (startDate && endDate) {
        periodText = `${new Date(startDate).toLocaleDateString('en-IN')}  to  ${new Date(endDate).toLocaleDateString('en-IN')}`;
      } else if (startDate) {
        periodText = `From: ${new Date(startDate).toLocaleDateString('en-IN')}`;
      } else if (endDate) {
        periodText = `Up to: ${new Date(endDate).toLocaleDateString('en-IN')}`;
      } else {
        periodText = 'All Transactions';
      }

      doc.fillColor('#e8eaf6').font('Helvetica').fontSize(9)
        .text(`Period: ${periodText}`, margin, 82, { width: contentWidth, align: 'center' });

      doc.fillColor('#1a237e').rect(margin, 92, contentWidth, 1.5).fill();
    };

    const drawTableHeader = (y) => {
      doc.fillColor('#e3f2fd').rect(tableLeft, y, tableWidth, 24).fill();
      doc.strokeColor('#90caf9').lineWidth(0.5).rect(tableLeft, y, tableWidth, 24).stroke();

      doc.fillColor('#1a237e').font('Helvetica-Bold').fontSize(8);
      let x = tableLeft;
      colHeaders.forEach((h, i) => {
        doc.text(h, x + 3, y + 7, { width: colWidths[i] - 6, align: i === 4 ? 'right' : 'center' });
        x += colWidths[i];
      });

      doc.fillColor('#000000');
      return y + 24;
    };

    const drawTableRow = (y, data, isAlt, isDebit) => {
      if (isAlt) {
        doc.fillColor('#f5f5f5').rect(tableLeft, y, tableWidth, 20).fill();
      }

      doc.strokeColor('#e0e0e0').lineWidth(0.3).rect(tableLeft, y, tableWidth, 20).stroke();
      doc.fillColor('#000000').fontSize(8).font('Helvetica');

      let x = tableLeft;
      data.forEach((d, i) => {
        let align = 'left';
        if (i === 0) align = 'center';
        if (i === 4) align = 'right';

        doc.text(String(d || ''), x + 3, y + 4, { width: colWidths[i] - 6, align });
        x += colWidths[i];
      });

      return y + 20;
    };

    const drawFooter = (page) => {
      const footerY = pageHeight - 25;
      doc.strokeColor('#cccccc').lineWidth(0.5)
        .moveTo(margin, footerY)
        .lineTo(pageWidth - margin, footerY)
        .stroke();

      doc.fillColor('#999999').fontSize(7).font('Helvetica')
        .text(`Generated on: ${new Date().toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'Asia/Kolkata' })}`, margin, footerY + 5, { width: contentWidth / 2 });

      if (myCompany) {
        doc.text(`${myCompany.name}`, margin, footerY + 5, { width: contentWidth, align: 'right' });
      }
    };

    drawPageHeader();

    let yPos = drawTableHeader(tableTop);
    let runningBalance = 0;
    let srNo = 1;

    sortedAsc.forEach((transaction, index) => {
      if (transaction.type === 'IN') {
        runningBalance += transaction.amount;
      } else {
        runningBalance -= transaction.amount;
      }

      if (yPos + 20 > pageHeight - 90) {
        doc.addPage();
        drawFooter(doc);
        drawPageHeader();
        yPos = drawTableHeader(tableTop);
      }

      const companyWorker = transaction.company?.name || transaction.worker?.name || '-';
      const formattedDate = new Date(transaction.paymentDate).toLocaleDateString('en-IN', { day: '2-digit', month: '2-digit', year: 'numeric' });

      let relatedInfo = '';
      const relatedParts = [];
      if (transaction.relatedBills?.length) {
        transaction.relatedBills.forEach(b => relatedParts.push(`Bill: ${b.billNumber}`));
      }
      if (transaction.relatedPurchases?.length) {
        transaction.relatedPurchases.forEach(p => relatedParts.push(`Purchase: ${p.purchaseBillNumber}`));
      }
      if (transaction.relatedDebitNotes?.length) {
        transaction.relatedDebitNotes.forEach(d => relatedParts.push(`Debit Note: ${d.debitNoteNumber}`));
      }
      if (transaction.relatedInterestNotes?.length) {
        transaction.relatedInterestNotes.forEach(i => relatedParts.push(`Interest Note: ${i.interestNoteNumber}`));
      }
      relatedInfo = relatedParts.join(', ');

      const fullDescription = transaction.description + (relatedInfo ? ` [${relatedInfo}]` : '');

      const amountText = transaction.type === 'IN'
        ? `+ ${transaction.amount.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`
        : `- ${transaction.amount.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`;

      yPos = drawTableRow(yPos, [
        srNo.toString(),
        formattedDate,
        fullDescription,
        companyWorker,
        amountText,
      ], index % 2 === 0, transaction.type === 'OUT');

      srNo++;
    });

    doc.strokeColor('#1a237e').lineWidth(1)
      .moveTo(tableLeft, yPos)
      .lineTo(tableLeft + tableWidth, yPos)
      .stroke();

    yPos += 5;
    doc.font('Helvetica-Bold').fontSize(8).fillColor('#1a237e')
      .text('Total Credit (IN)', tableLeft, yPos, { width: colWidths[0] + colWidths[1] + colWidths[2], align: 'right' });
    doc.text(`${totalIn.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, tableLeft + tableWidth - colWidths[4], yPos, { width: colWidths[4], align: 'right' });

    yPos += 16;
    doc.text('Total Debit (OUT)', tableLeft, yPos, { width: colWidths[0] + colWidths[1] + colWidths[2], align: 'right' });
    doc.text(`${totalOut.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, tableLeft + tableWidth - colWidths[4], yPos, { width: colWidths[4], align: 'right' });

    yPos += 18;
    doc.rect(tableLeft, yPos - 2, tableWidth, 20).fill('#1a237e');
    doc.fillColor('#ffffff').fontSize(9)
      .text('Net Balance', tableLeft, yPos + 2, { width: colWidths[0] + colWidths[1] + colWidths[2], align: 'right' });
    doc.text(`${netBalance.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, tableLeft + tableWidth - colWidths[4], yPos + 2, { width: colWidths[4], align: 'right' });

    yPos += 30;
    doc.fillColor('#000000').font('Helvetica').fontSize(7)
      .text(`Total Transactions: ${transactions.length}  |  Credits: ${transactions.filter(t => t.type === 'IN').length}  |  Debits: ${transactions.filter(t => t.type === 'OUT').length}`, tableLeft, yPos, { width: contentWidth, align: 'center' });

    drawFooter(doc);

    doc.end();
    log(`Exported ${transactions.length} transactions to PDF`, 'info');
  } catch (error) {
    log(`Error exporting transactions to PDF: ${error.message}`, 'error');
    if (!res.headersSent) {
      res.status(500).json({ message: 'Server error while exporting transactions to PDF.' });
    }
  }
};

